# Пользователь вводит строку, состоящую из букв, цифр и других символов. Напишите
# функцию, которая находит сумму цифр в строке. Если в строке цифр нет, то функция
# должна вернуть 0.
#
# Пример данных:
# "Вчера мне было 17 годиков, а сегодня мне уже 18 лет!"


def digits_sum(text: str) -> int:
    return sum(map(int, filter(str.isdecimal, text)))


if __name__ == "__main__":
    print(f"Сумма цифр: {digits_sum(input('Введите строку: '))}")
